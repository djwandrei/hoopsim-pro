import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { createForgeEvidence } from './lib/forge-evidence.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const data = path.join(root, 'integration/site/tools/swishiq-studio/data');
const release = path.join(data, 'v4/releases/v4-site-12ad90dc8710');
const json = async file => JSON.parse(await readFile(file, 'utf8'));
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const registry = await json(path.join(release, 'registry.json'));
const entries = registry.packages.filter(p => p.scope.kind === 'exact-season');
const context = await json(path.join(data, 'public-player-context-v2.json'));
const inputs = new Map();
for (const entry of entries) {
  const bytes = await readFile(path.join(release, entry.projectionIndexPath));
  if (sha(bytes) !== entry.indexSha256) throw new Error('Projection index integrity failed.');
  const index = JSON.parse(bytes);
  const part = async id => {
    const descriptor = index.artifacts.find(a => a.artifactId === id);
    const content = await readFile(path.join(release, descriptor.path));
    if (sha(content) !== descriptor.sha256) throw new Error(`Source integrity failed: ${id}`);
    return JSON.parse(content).records;
  };
  const [seasons, base, clutch, hustle, defense, combine] = await Promise.all(['player-seasons', 'stats-nba-com-player-base', 'stats-nba-com-player-clutch-base', 'stats-nba-com-player-hustle', 'stats-nba-com-player-defense-dash-gt15', 'draft-combine-observations'].map(part));
  inputs.set(entry, { seasons, base, clutch, hustle, defense, combine });
}
const combine = [...inputs.values()].flatMap(p => p.combine), pins = [];
const output = path.join(root, 'public/studio-assets/forge/ratings');
await mkdir(output, { recursive: true });
for (const [entry, parts] of inputs) {
  const year = entry.scope.seasonStartYear;
  const doc = createForgeEvidence(year, entry.packageVersion, parts, context, combine);
  const bytes = Buffer.from(JSON.stringify(doc) + '\n'), hash = sha(bytes), file = `${year}-${hash.slice(0, 12)}.json`;
  await writeFile(path.join(output, file), bytes);
  pins.push({ year, packageVersion: entry.packageVersion, url: `/studio-assets/forge/ratings/${file}`, sha256: hash, bytes: bytes.length });
  console.log(year, JSON.stringify(doc.coverage), `${bytes.length} bytes`);
}
await writeFile(path.join(root, 'src/components/forge/forgeEvidenceRelease.js'), `// Generated by scripts/build-forge-evidence.mjs from reviewed local sources.\nexport const FORGE_EVIDENCE_RELEASE = ${JSON.stringify(pins, null, 2)};\n`);
