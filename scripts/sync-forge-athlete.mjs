import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Local asset transfer only. The draft rules, team designs and earlier assets
// are preserved. Source must be a validated pose-studio authoring directory.
const project = fileURLToPath(new URL('..', import.meta.url));
const source = path.resolve(process.argv[2] || 'C:/Users/djwan/Documents/Codex/2026-10-07/basketball-silhouette');
const target = path.join(project, 'public/studio-assets/forge/athlete');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const report = name => readFile(path.join(source, name), 'utf8').then(JSON.parse);
const elements = ['body', 'jersey', 'shorts', 'right-shoe', 'left-shoe', 'basketball', 'head-neck', 'exposed-upper-body', 'right-arm', 'left-arm', 'headband', 'right-sleeve', 'left-sleeve'];
const [model, rawRig, presets, validation, wardrobe, controller] = await Promise.all([
  readFile(path.join(source, 'basketball-athlete-outfit.glb')),
  readFile(path.join(source, 'athlete-rig-data.js'), 'utf8'),
  report('basketball-preset-poses.json'), report('articulation800k-independent-rig-validation.json'),
  report('wardrobe-validation.json'), report('pose-controller-validation.json'),
]);
const rig = JSON.parse(rawRig.slice(rawRig.indexOf('=') + 1).trim().replace(/;$/, ''));
assert.equal(validation.status, 'passed'); assert.equal(wardrobe.status, 'passed'); assert.equal(controller.status, 'passed');
assert.equal(validation.sourceSha256, rig.sourceSha256);
assert.equal(validation.verifiedInputs['athlete-rig-data.js'], hash(Buffer.from(rawRig)));
assert.equal(validation.verifiedInputs['basketball-preset-poses.json'], hash(Buffer.from(await readFile(path.join(source, 'basketball-preset-poses.json')))));
assert.equal(wardrobe.outfitSha256, hash(model)); assert.equal(wardrobe.maximumTriangles, 800000);
assert.equal(model.readUInt32LE(0), 0x46546c67); assert.equal(model.readUInt32LE(8), model.length);
const doc = JSON.parse(model.subarray(20, 20 + model.readUInt32LE(12)).toString('utf8'));
const names = doc.meshes.map(mesh => mesh.name); assert.deepEqual(names, elements);
const triangles = doc.meshes.reduce((sum, mesh) => sum + mesh.primitives.reduce((total, primitive) => total + doc.accessors[primitive.indices].count / 3, 0), 0);
assert.equal(triangles, 800000); assert.equal(rig.bones.length, 48); assert.equal(doc.skins[0].joints.length, 47);
assert.deepEqual(doc.skins[0].joints.map(index => doc.nodes[index].name), rig.bones.slice(0, rig.ballIndex).map(bone => bone.name));
const dunk = presets.presets.find(item => item.id === 'dunk'); assert.ok(dunk);
const binding = Buffer.from(JSON.stringify({ version: 2, modelSha256: hash(model), sourceSha256: rig.sourceSha256,
  bones: rig.bones.map(({ name, parent, pivot, axes }) => ({ name, parent, pivot, axes })), pose: dunk.pose }, null, 2) + '\n');
const release = { version: 'articulation800k-20261010', triangles, controls: rig.bones.length, skinJoints: doc.skins[0].joints.length, elements,
  sourceSha256: rig.sourceSha256, model: { path: `basketball-athlete-outfit-${hash(model).slice(0, 12)}.glb`, bytes: model.length, sha256: hash(model) },
  rig: { path: `dunk-rig-${hash(binding).slice(0, 12)}.json`, bytes: binding.length, sha256: hash(binding) } };
// Copy the reviewed model's texture mapping as well as its geometry. Forge
// supplies its existing donor colors and uniform images to this shared atlas.
const atlas = await readFile(path.join(source, 'uniform-atlas.js'), 'utf8');
const start = atlas.indexOf('  function panel('), end = atlas.indexOf('  globalThis.SILHOUETTE_ATLAS');
assert.ok(start > 0 && end > start);
const atlasModule = '// Generated by scripts/sync-forge-athlete.mjs from the reviewed model UV atlas.\n' +
  atlas.slice(start, end).replace(/^  /gm, '') +
  '\nexport default function forgeUniformAtlas(element, item, loaded) {\n  return create(element, { color: element === "shorts" ? item.shorts : item.primary, trimColor: item.accent }, loaded);\n}\n';
release.atlasSha256 = hash(Buffer.from(atlasModule));
await mkdir(target, { recursive: true });
for (const [item, bytes] of [[release.model, model], [release.rig, binding]]) {
  const dest = path.join(target, item.path), existing = await readFile(dest).catch(error => { if (error.code !== 'ENOENT') throw error; });
  if (existing) assert.equal(hash(existing), item.sha256, 'A content-addressed athlete asset must never be overwritten with different bytes');
  else await writeFile(dest, bytes);
}
const originalCatalog = JSON.parse(await readFile(path.join(target, 'uniform-catalog.json'), 'utf8'));
const sourceCatalog = await report('uniform-source-manifest.json');
assert.deepEqual(sourceCatalog.items.map(item => item.id), originalCatalog.items.map(item => item.id));
assert.deepEqual(sourceCatalog.teams, originalCatalog.teams);
const originalItems = new Map(originalCatalog.items.map(item => [item.id, item]));
const uniformItems = []; let uniformImages = 0, uniformBytes = 0;
const uniformFolder = 'uniforms-articulation800k';
await mkdir(path.join(target, uniformFolder), { recursive: true });
for (const item of sourceCatalog.items) {
  const raw = await readFile(path.join(source, item.script), 'utf8');
  const assignment = raw.indexOf(' = ', raw.indexOf(' = ') + 3);
  assert.ok(assignment > 0);
  const payload = JSON.parse(raw.slice(assignment + 3).trim().replace(/;$/, ''));
  const transferred = { ...item, layout: payload.layout }; delete transferred.script;
  for (const side of ['image', 'front', 'back']) {
    const match = /^data:image\/(jpeg|png|webp);base64,([A-Za-z0-9+/=\r\n]+)$/.exec(payload[side]);
    assert.ok(match, `The reviewed ${item.id} ${side} image is missing`);
    const bytes = Buffer.from(match[2], 'base64'), sha = hash(bytes), prior = originalItems.get(item.id)[side];
    const priorBytes = prior ? await readFile(path.join(target, prior)) : null;
    if (priorBytes && hash(priorBytes) === sha) transferred[side] = prior;
    else {
      const extension = match[1] === 'jpeg' ? 'jpg' : match[1];
      const relative = `${uniformFolder}/${item.id}-${side}-${sha.slice(0, 12)}.${extension}`;
      const dest = path.join(target, relative), existing = await readFile(dest).catch(error => { if (error.code !== 'ENOENT') throw error; });
      if (existing) assert.equal(hash(existing), sha); else await writeFile(dest, bytes);
      transferred[side] = relative;
    }
    uniformImages++; uniformBytes += bytes.length;
  }
  uniformItems.push(transferred);
}
const catalogBytes = Buffer.from(JSON.stringify({ version: sourceCatalog.version, season: sourceCatalog.season,
  teams: sourceCatalog.teams, editions: sourceCatalog.editions, referenceRevision: sourceCatalog.referenceRevision, items: uniformItems }, null, 2) + '\n');
release.catalog = { path: `uniform-catalog-${hash(catalogBytes).slice(0, 12)}.json`, bytes: catalogBytes.length, sha256: hash(catalogBytes) };
await writeFile(path.join(target, release.catalog.path), catalogBytes);
await writeFile(path.join(project, 'src/components/forge/forgeAthleteRelease.js'), '// Generated by scripts/sync-forge-athlete.mjs from the validated local model.\nexport const FORGE_ATHLETE_RELEASE = ' + JSON.stringify(release, null, 2) + ';\n');
await writeFile(path.join(project, 'src/components/forge/forgeUniformAtlas.js'), atlasModule);
await writeFile(path.join(target, 'asset-receipt.json'), JSON.stringify({ ...release, source: 'local validated basketball-silhouette authoring workspace', uniforms: uniformItems.length, uniformImages, uniformBytes,
  preserved: ['draft rules', 'team and edition identities', 'original uniform catalog and images', 'separate garment/accessory names', 'earlier model and pose assets'], deployed: false }, null, 2) + '\n');
console.log(JSON.stringify({ status: 'passed', release, uniforms: uniformItems.length, uniformImages, deployed: false }));
