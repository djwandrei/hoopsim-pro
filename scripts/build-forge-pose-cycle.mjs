import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { FORGE_ATHLETE_RELEASE as release } from '../src/components/forge/forgeAthleteRelease.js';

// Transfer three already-reviewed poses into a small content-addressed asset.
// The model, existing rig, presets and original validation receipts stay intact.
const project = fileURLToPath(new URL('../', import.meta.url));
const source = path.resolve(process.argv[2] || 'C:/Users/djwan/Documents/Codex/2026-10-07/basketball-silhouette');
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const [rawRig, presetBytes, validationBytes, modelBytes, bindingBytes] = await Promise.all([
  readFile(path.join(source, 'athlete-rig-data.js'), 'utf8'),
  readFile(path.join(source, 'basketball-preset-poses.json')),
  readFile(path.join(source, 'articulation800k-independent-rig-validation.json')),
  readFile(path.join(source, 'basketball-athlete-outfit.glb')),
  readFile(path.join(project, 'public/studio-assets/forge/athlete', release.rig.path)),
]);
const rig = JSON.parse(rawRig.slice(rawRig.indexOf('=') + 1).trim().replace(/;$/, ''));
const presets = JSON.parse(presetBytes), validation = JSON.parse(validationBytes), binding = JSON.parse(bindingBytes);
assert.equal(sha(modelBytes), release.model.sha256, 'Authoring model must still match the shipped Forge model');
assert.equal(sha(bindingBytes), release.rig.sha256);
assert.equal(validation.status, 'passed');
assert.equal(validation.verifiedInputs['athlete-rig-data.js'], sha(Buffer.from(rawRig)));
assert.equal(validation.verifiedInputs['basketball-preset-poses.json'], sha(presetBytes));
assert.equal(rig.sourceSha256, release.sourceSha256);
assert.equal(rig.bones.length, release.controls);
assert.equal(JSON.stringify(rig.bones.map(({ name, parent, pivot, axes }) => ({ name, parent, pivot, axes }))), JSON.stringify(binding.bones));
const vector = row => Array.isArray(row) && row.length === 3 && row.every(Number.isFinite);
const poses = ['dunk', 'jump-shot', 'defense'].map(id => {
  const preset = presets.presets.find(item => item.id === id);
  assert.ok(preset, `Missing reviewed ${id} preset`);
  assert.equal(preset.pose.rotations.length, release.controls);
  assert.equal(preset.pose.translations.length, release.controls);
  assert.ok(preset.pose.rotations.every(vector) && preset.pose.translations.every(vector));
  assert.equal(preset.pose.ballAttached, true, 'All cycle poses use the existing hand attachment');
  assert.equal(typeof preset.pose.ballVisible, 'boolean');
  return { id, label: preset.label, pose: preset.pose };
});
assert.equal(JSON.stringify(poses[0].pose), JSON.stringify(binding.pose), 'The opening dunk must be identical to the current rig');
const doc = {
  version: 1, modelSha256: release.model.sha256, sourceSha256: release.sourceSha256,
  controls: release.controls, rotationsPerPose: 2, poses,
  provenance: { presetSha256: sha(presetBytes), rigSha256: sha(Buffer.from(rawRig)), validationSha256: sha(validationBytes), method: 'Exact authored pose transfer; no geometry or source changes' },
};
const bytes = Buffer.from(JSON.stringify(doc, null, 2) + '\n');
const hash = sha(bytes), name = `pose-cycle-${hash.slice(0, 12)}.json`;
const target = path.join(project, 'public/studio-assets/forge/athlete', name);
const existing = await readFile(target).catch(error => { if (error.code !== 'ENOENT') throw error; });
if (existing) assert.equal(sha(existing), hash, 'Do not overwrite a content-addressed asset with different bytes');
else await writeFile(target, bytes);
const pin = { path: name, bytes: bytes.length, sha256: hash, modelSha256: release.model.sha256, rotationsPerPose: 2, poses: poses.map(item => item.id) };
await writeFile(path.join(project, 'src/components/forge/forgePoseRelease.js'), '// Generated by scripts/build-forge-pose-cycle.mjs from the validated authored presets.\nexport const FORGE_POSE_RELEASE = ' + JSON.stringify(pin, null, 2) + ';\n');
console.log(JSON.stringify({ status: 'passed', ...pin, deployed: false }));
